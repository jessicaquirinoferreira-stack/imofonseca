export function normalizePropertyImages(property: Property): Property {
  const seedMatch = SEED_PROPERTIES.find(
    (s) => s.id === property.id || s.slug === property.slug
  );
  const filteredImages = (property.images || []).filter(
    (img) => !BANNED_LOGO_SLIDE_URLS.has(img)
  );

  if (seedMatch) {
    const primaryFacade = seedMatch.images[0];
    const rest = filteredImages.filter((img) => img !== primaryFacade);
    return {
      ...property,
      ...seedMatch,
      title:
        property.title === 'Parque 1453 (Vital Construtora)'
          ? 'Residencial Parque 1453'
          : seedMatch.title,
      highlight: seedMatch.highlight,
      description: seedMatch.description,
      specs: seedMatch.specs,
      images: [primaryFacade, ...rest],
    };
  }

  return {
    ...property,
    images: filteredImages.length > 0 ? filteredImages : property.images,
  };
}

export function hasPropertyPrice(property?: Property | Partial<Property> | null): boolean {
  if (!property) return false;
  if (typeof property.priceValue === 'number' && property.priceValue > 0) {
    if (
      property.priceLabel &&
      property.priceLabel.toLowerCase().includes('sob consulta')
    ) {
      return false;
    }
    return true;
  }
  return false;
}

export function buildPropertyWhatsAppSummary(property: Property): string {
  const priceInfo = hasPropertyPrice(property)
    ? property.priceLabel
    : 'Sob Consulta / Condições Especiais';
  return `🏢 *${property.title}*
📍 Localização: ${property.location}
📐 Área: ${property.area} | 🛏️ Dormitórios: ${property.bedrooms} | 🚗 Vagas: ${property.parking}
💰 Valor: ${priceInfo}
🏗️ Construtora: ${property.builder} (Status: ${property.status})`;
}

export function getPropertyWhatsAppLink(
  property: Property,
  whatsappNumber: string,
  context: 'simulacao' | 'consulta' | string = 'consulta'
): string {
  const cleanNumber = whatsappNumber.replace(/\D/g, '');
  const summary = buildPropertyWhatsAppSummary(property);
  let message = '';

  if (context === 'simulacao') {
    message = `🏛️ *IMOBILIÁRIA FONSECA & CÂNDIDO*
Olá! Gostaria de fazer uma simulação de financiamento e receber a tabela atualizada para o imóvel:

${summary}

Por favor, me envie as opções de entrada, fluxo durante a obra e parcelamento bancário!`;
  } else {
    message = `🏛️ *IMOBILIÁRIA FONSECA & CÂNDIDO*
Olá! Tenho interesse no seguinte empreendimento:

${summary}

Gostaria de agendar uma apresentação exclusiva e saber mais detalhes sobre unidades disponíveis e valores!`;
  }

  return `https://wa.me/${cleanNumber}?text=${encodeURIComponent(message)}`;
}


